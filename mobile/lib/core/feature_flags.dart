/// Функции, реализованные в коде, но намеренно закрытые от пользователя.
///
/// Это не «мёртвый код» — вся реализация на месте и компилируется. Флаги
/// стоят на *точках входа в UI*: пока флаг `false`, пользователь видит
/// исчезающее сообщение «в разработке» вместо экрана или действия.
///
/// Почему флаги, а не удаление кода: работа доведена до рабочего состояния и
/// покрыта тестами на бэкенде. Удалить — значит потерять её и переписывать
/// заново. Один `true` возвращает функцию обратно целиком.
///
/// **Как включить обратно** — поставить флаг в `true` и выполнить пункты из
/// комментария к нему. Ничего другого править не нужно.
class FeatureFlags {
  const FeatureFlags._();

  /// Экспорт аналитики в файл (сейчас PDF; Excel не реализован вовсе).
  ///
  /// Закрывает: кнопку «Экспортировать отчёт» на экране «Статистика» и пункт
  /// «Экспорт отчёта» в «Настройки → Данные». Сам экран «Статистика» и
  /// диаграмма расходов на Главной работают как обычно — под флагом только
  /// выгрузка.
  ///
  /// Включение: достаточно `true`. `PdfExportService` рабочий, зависимости
  /// `pdf` и `printing` остаются в pubspec.
  static const bool fileExport = false;

  /// Облачная синхронизация между устройствами (push/pull через сервер).
  ///
  /// **Включена.** Ради неё поднимается бэкенд: без обмена данными вход даёт
  /// пустое приложение, а «те же данные на другом устройстве» невозможны.
  ///
  /// Что за этим стоит: первый цикл идёт сразу после входа
  /// (`AuthenticateAndSyncUseCase`), дальше — `SyncScheduler`, который
  /// запускается на старте оболочки (`syncBootstrapProvider` в `HomeShell`)
  /// и повторяет цикл по таймеру, при возврате связи и при возвращении
  /// приложения из фона. Локальная Isar остаётся источником истины: без сети
  /// приложение работает целиком, изменения уезжают на сервер при первой
  /// возможности.
  ///
  /// Выключение вернёт офлайн-режим: вход и регистрация продолжат работать,
  /// но данные останутся на устройстве. Сид локальных категорий при этом
  /// снова включается сам — см. `AuthenticateAndSyncUseCase._resetLocal`.
  static const bool cloudSync = true;

  /// Семья: приглашения и общий доступ к данным нескольких пользователей.
  ///
  /// Зависит от [cloudSync] — без обмена данными второй участник семьи
  /// физически не увидит операции первого, поэтому включать в одиночку
  /// бессмысленно.
  ///
  /// Включение: `true` **и** [cloudSync] `true`.
  static const bool family = false;
}
